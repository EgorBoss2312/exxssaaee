def _join(parts: list[str]) -> str:
    return "\n\n".join(p.strip() for p in parts if p.strip())


def _para(topic: str, detail: str) -> str:
    return (
        f"{topic}. {detail} На предприятии {COMPANY} данные требования согласованы с "
        f"производственной программой, системой менеджмента качества и действующим "
        f"законодательством Российской Федерации. Нарушение установленного порядка "
        f"фиксируется в журнале замечаний и рассматривается на оперативных совещаниях "
        f"с участием ответственных исполнителей."
    )


def _appendix(code: str, sections: list[tuple[str, str]]) -> str:
    lines = [f"ПРИЛОЖЕНИЕ А к документу {code}", ""]
    for i, (title, body) in enumerate(sections, 1):
        lines.append(f"П.{i}. {title}")
        lines.append(body)
        lines.append(
            _para(
                "Контроль исполнения",
                f"По разделу «{title}» ответственный специалист ежемесячно формирует "
                f"отчёт о выполнении мероприятий и направляет его непосредственному "
                f"руководителю и в архив локальных актов.",
            )
        )
    return _join(lines)


def _doc(
    title: str,
    fname: str,
    roles: list[str],
    code: str,
    sections: list[tuple[str, str]],
    appendix_sections: list[tuple[str, str]],
) -> tuple[str, str, list[str], str]:
    body_parts = [
        title.upper(),
        f"Код документа: {code}",
        "",
        COMPANY_FULL,
        "",
        HDR,
        "",
    ]
    for i, (sec_title, sec_body) in enumerate(sections, 1):
        body_parts.append(f"{i}. {sec_title}")
        body_parts.append(sec_body)
        body_parts.append(
            _para(
                f"Примечание к п. {i}",
                f"При выполнении требований раздела «{sec_title}» используются "
                f"утверждённые формы первичных документов, шаблоны отчётности и "
                f"записи информационных систем предприятия (1С, MES, портал EDDA).",
            )
        )
    body_parts.append(FOOTER)
    body_parts.append(_appendix(code, appendix_sections))
    return title, fname, roles, _join(body_parts)


